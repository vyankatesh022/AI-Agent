"""Data models and representations for LLM interactions."""

from enum import Enum
from typing import Any

from pydantic import BaseModel, Field


class LLMProviderType(str, Enum):
    """Enumeration of supported LLM providers."""

    OPENAI = "openai"
    GEMINI = "gemini"


class ToolCall(BaseModel):
    """Representation of a requested tool execution."""

    name: str = Field(description="Name of the registered tool to call")
    args: dict[str, Any] = Field(
        default_factory=dict,
        description="Arguments passed to the tool",
    )


class LLMResponse(BaseModel):
    """Standardized response from an LLM provider."""

    content: str = Field(
        default="",
        description="Text content generated by the model",
    )
    tool_calls: list[ToolCall] = Field(
        default_factory=list,
        description="List of tool calls requested by the model",
    )
