"""Secure filesystem storage manager for uploaded document files."""

import logging
import uuid
from pathlib import Path

logger = logging.getLogger(__name__)


class DocumentStorage:
    """Safely manages reading, writing, and deleting physical files on disk.

    Enforces:
    - Path traversal defenses (verifies paths stay within base storage directory)
    - Generated internal filenames (never stores using client-controlled paths)
    """

    def __init__(self, base_directory: str = "data/documents") -> None:
        self.base_path = Path(base_directory).resolve()
        self.base_path.mkdir(parents=True, exist_ok=True)

    def save_file(self, content: bytes, doc_id: uuid.UUID) -> str:
        """Persist file content safely under a generated document identifier.

        Args:
            content: Raw byte content of the document.
            doc_id: Authoritative UUID generated by the server.

        Returns:
            Resolved absolute path to the stored file.
        """
        safe_filename = f"{doc_id}.pdf"
        target_path = (self.base_path / safe_filename).resolve()

        # Path traversal guard
        if not target_path.is_relative_to(self.base_path):
            raise ValueError("Path traversal attempt detected in storage path.")

        with open(target_path, "wb") as f:
            f.write(content)

        logger.debug("Safely stored document at %s", target_path)
        return str(target_path)

    def read_file(self, storage_path: str) -> bytes:
        """Read document bytes from a safe storage path."""
        path = Path(storage_path).resolve()
        if not path.is_relative_to(self.base_path) or not path.is_file():
            raise FileNotFoundError(f"File not found at storage path: {storage_path}")

        with open(path, "rb") as f:
            return f.read()

    def delete_file(self, storage_path: str) -> bool:
        """Delete document file from disk if it exists."""
        try:
            path = Path(storage_path).resolve()
            if path.is_relative_to(self.base_path) and path.is_file():
                path.unlink()
                logger.debug("Deleted document file at %s", path)
                return True
        except Exception as exc:
            logger.warning("Error deleting file at %s: %s", storage_path, exc)
        return False
