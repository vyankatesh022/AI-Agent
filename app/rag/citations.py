"""Provenance citation models, builders, and validation against authoritative source maps."""

import logging
import re
from dataclasses import asdict, dataclass
from typing import Any

logger = logging.getLogger(__name__)


@dataclass
class Citation:
    """Verifiable reference to a specific source document page and chunk."""

    document_id: str
    filename: str
    page_number: int
    chunk_index: int
    snippet: str

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class SourceReference:
    """Authoritative source metadata tagged with an identifier (e.g. S1, S2)."""

    source_id: str
    document_id: str
    filename: str
    page_number: int
    chunk_id: str
    snippet: str

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class CitationValidationResult:
    """Outcome of citation verification against retrieved sources."""

    verified_sources: list[SourceReference]
    valid_citations: list[str]
    invalid_citations: list[str]
    cleaned_text: str

    @property
    def is_valid(self) -> bool:
        """True if all citations made in the text correspond to actual sources."""
        return len(self.invalid_citations) == 0


class CitationBuilder:
    """Constructs structured citations and authoritative source reference maps."""

    @staticmethod
    def build_citations(
        chunks_with_scores: list[tuple[dict[str, Any], float]],
    ) -> list[Citation]:
        """Transform search results into structured citations (backward compatible)."""
        citations: list[Citation] = []
        seen = set()

        for chunk_meta, _ in chunks_with_scores:
            doc_id = str(chunk_meta.get("document_id", ""))
            filename = chunk_meta.get("filename", "unknown.pdf")
            page_num = int(chunk_meta.get("page_number", 1))
            chunk_idx = int(chunk_meta.get("chunk_index", 0))
            text = chunk_meta.get("text", "")

            snippet = text[:150] + "..." if len(text) > 150 else text

            key = (doc_id, page_num, chunk_idx)
            if key not in seen:
                seen.add(key)
                citations.append(
                    Citation(
                        document_id=doc_id,
                        filename=filename,
                        page_number=page_num,
                        chunk_index=chunk_idx,
                        snippet=snippet,
                    )
                )

        return citations

    @staticmethod
    def format_inline_source(filename: str, page_number: int) -> str:
        """Standard citation string format for LLM prompt instruction."""
        return f"[Source: {filename}, Page {page_number}]"


class CitationValidator:
    """Validates citations generated by LLM against authoritative retrieved sources."""

    # Matches [S1], [S2], [s1] and variations
    SOURCE_ID_PATTERN = re.compile(r"\[(S\d+)\]", re.IGNORECASE)

    # Also captures legacy [Source: filename, Page X]
    LEGACY_PATTERN = re.compile(
        r"\[Source:\s*([^,\]]+),\s*Page\s*(\d+)\]", re.IGNORECASE
    )

    @classmethod
    def validate_citations(
        cls,
        text: str,
        source_map: dict[str, SourceReference],
    ) -> CitationValidationResult:
        """Inspect generated text and enforce that cited sources exist in source_map.

        Guarantees:
        - If LLM invents [S99] when only S1, S2 exist, [S99] is flagged as invalid
          and stripped from the verified source list.
        - Free-form hallucinations are rejected.
        - Authoritative metadata is attached from source_map, never trusted from text.

        Args:
            text: Raw generated response text from LLM.
            source_map: Mapping of source_id ('S1') to authoritative SourceReference.

        Returns:
            CitationValidationResult with verified sources and cleaned text.
        """
        if not text:
            return CitationValidationResult(
                verified_sources=[],
                valid_citations=[],
                invalid_citations=[],
                cleaned_text="",
            )

        # Normalize source_map keys to uppercase
        norm_map = {k.upper(): v for k, v in source_map.items()}

        valid_citations: list[str] = []
        invalid_citations: list[str] = []
        verified_sources_dict: dict[str, SourceReference] = {}

        # 1. Check [S1], [S2] pattern
        found_matches = cls.SOURCE_ID_PATTERN.findall(text)
        for match in found_matches:
            tag = match.upper()
            if tag in norm_map:
                if tag not in valid_citations:
                    valid_citations.append(tag)
                verified_sources_dict[tag] = norm_map[tag]
            else:
                if tag not in invalid_citations:
                    invalid_citations.append(tag)

        # 2. Check legacy [Source: filename, Page X] pattern
        for filename_match, page_match in cls.LEGACY_PATTERN.findall(text):
            target_fn = filename_match.strip().lower()
            target_page = int(page_match)
            matched = False
            for src_id, ref in norm_map.items():
                if ref.filename.lower() == target_fn and ref.page_number == target_page:
                    if src_id not in valid_citations:
                        valid_citations.append(src_id)
                    verified_sources_dict[src_id] = ref
                    matched = True
                    break
            if not matched:
                invalid_citations.append(
                    f"[Source: {filename_match}, Page {page_match}]"
                )

        # 3. Clean invalid source IDs from text so users aren't misled by nonexistent citations
        cleaned_text = text
        for inv in invalid_citations:
            if inv.startswith("S"):
                cleaned_text = re.sub(
                    rf"\[{re.escape(inv)}\]", "", cleaned_text, flags=re.IGNORECASE
                )

        # Sort verified sources by ID order (S1, S2...)
        verified_sources = [
            verified_sources_dict[k]
            for k in sorted(
                verified_sources_dict.keys(),
                key=lambda x: int(x[1:]) if x[1:].isdigit() else 999,
            )
        ]

        if invalid_citations:
            logger.warning(
                "Detected and rejected %d hallucinated citations: %s",
                len(invalid_citations),
                invalid_citations,
            )

        return CitationValidationResult(
            verified_sources=verified_sources,
            valid_citations=valid_citations,
            invalid_citations=invalid_citations,
            cleaned_text=cleaned_text.strip(),
        )
